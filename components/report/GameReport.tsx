import { steamArtworkUrl } from "@/lib/gameSearch";
import Image from "next/image";
import Link from "next/link";
import type { SteamAssessment } from "@/lib/assessmentEngine";
import type { SteamGameMetadata } from "@/lib/steamMetadata";
import type { Category } from "@/lib/assessmentRules";
import { gameReportPath } from "@/lib/gameSearch";
import { australianRatingLabel, positiveSteamTags, reportOverview } from "@/lib/reportPresentation";
import ReportActions, { SteamStoreLink } from "./ReportActions";
import { SITE_URL } from "@/lib/siteUrl";
import { ReportFinding, ReportSection, ReportStatus } from "./ReportSections";

type Rating = SteamAssessment["officialClassifications"][number];
const content: Category[] = ["violence", "graphicViolence", "strongLanguage", "sexualContent", "substances", "horror", "gambling", "matureThemes"];
const sections = [
  ["classifications", "Age classifications"], ["content", "Content suitability"],
  ["online", "Online safety"], ["spending", "Spending"], ["positive", "Positive gameplay"], ["transparency", "How this report works"],
];

function RatingCard({ title, rating, description, australian = false }: {
  title: string; rating?: Rating | null; description?: string; australian?: boolean;
}) {
  return <article className="rounded-xl border border-[#e8ddee] bg-[#fcfaff] p-4">
    <h3 className="font-bold">{title}</h3>
    {rating ? <>
      <p className="mt-1 text-2xl font-bold text-[#4c2b66]">{australian ? australianRatingLabel(rating.rating) : rating.rating.toUpperCase()}</p>
      {rating.descriptors && <p className="mt-2 whitespace-pre-line text-sm text-[#514960]">{rating.descriptors}</p>}
    </> : <p className="mt-2 text-sm text-[#514960]">Unavailable in the retrieved Steam data.</p>}
    {description && <p className="mt-2 text-sm text-[#514960]">{description}</p>}
  </article>;
}

function Classifications({ assessment }: { assessment: SteamAssessment }) {
  const otherBoards = assessment.officialClassifications.filter(({ authority }) => !/^(acb|oflc)$/i.test(authority));
  const otherSteam = assessment.steamGeneratedRatings.filter(({ authority }) => !/^steam_australia$/i.test(authority));
  return <ReportSection id="classifications" title="Age classifications">
    <div className="grid gap-3 sm:grid-cols-2">
      <RatingCard title="Australian Classification Board" rating={assessment.australianOfficialClassification} australian
        description="Official classification as reported by Steam." />
      <RatingCard title="Steam-generated Australian rating" rating={assessment.steamAustralianRating} australian
        description="Generated by Steam. This is separate from an Australian Classification Board decision." />
    </div>
    <details className="mt-4 border-t border-[#eee7f2] pt-1 text-sm">
      <summary className="min-h-11 cursor-pointer py-3 font-bold text-[#563569]">Other official classifications</summary>
      {otherBoards.length ? <div className="grid gap-3 sm:grid-cols-2">{otherBoards.map((rating) =>
        <RatingCard key={rating.authority} title={rating.authority.toUpperCase()} rating={rating} />)}</div>
        : <p className="text-[#514960]">No other official classifications were available in the retrieved data.</p>}
    </details>
    {otherSteam.length > 0 && <details className="border-t border-[#eee7f2] pt-1 text-sm">
      <summary className="min-h-11 cursor-pointer py-3 font-bold text-[#563569]">Other Steam-generated ratings</summary>
      <div className="grid gap-3 sm:grid-cols-2">{otherSteam.map((rating) =>
        <RatingCard key={rating.authority} title={rating.authority.replace(/^steam_/i, "").replaceAll("_", " ").toUpperCase()} rating={rating} />)}</div>
    </details>}
    {assessment.otherRatings.length > 0 && <details className="border-t border-[#eee7f2] pt-1 text-sm">
      <summary className="min-h-11 cursor-pointer py-3 font-bold text-[#563569]">Ratings with unverified authorities</summary>
      <p className="mb-3 text-[#514960]">Steam returned these identifiers. PlaySafe has not verified their authorities or used them to generate findings.</p>
      <div className="grid gap-3 sm:grid-cols-2">{assessment.otherRatings.map((rating) =>
        <RatingCard key={rating.authority} title={rating.authority.toUpperCase()} rating={rating} />)}</div>
    </details>}
  </ReportSection>;
}

export default function GameReport({ game, assessment, incomplete, staleRetrievedAt }: {
  game: SteamGameMetadata & { title: string }; assessment: SteamAssessment; incomplete: boolean; staleRetrievedAt?: string;
}) {
  const overview = reportOverview(assessment.categories);
  const positive = positiveSteamTags(game.tags);
  const multiplayer = [...new Set(game.multiplayer?.map(({ name }) => name))];
  const headerImage = steamArtworkUrl(game.headerImage);
  const findings = (categories: Category[]) => <div className="grid gap-3 sm:grid-cols-2">
    {assessment.categories.filter(({ category }) => categories.includes(category)).map((finding) =>
      <ReportFinding key={finding.category} finding={finding} />)}
  </div>;

  return (
    <main id="main-content" className="mx-auto w-full max-w-5xl flex-1 space-y-5 px-4 pb-14 pt-6 sm:space-y-6 sm:px-8 sm:pt-10">
      <Link href="/" className="inline-flex min-h-11 items-center font-bold text-[#563569] underline underline-offset-4">← Search for another game</Link>
      <header className="grid overflow-hidden rounded-3xl border border-[#e8ddee] bg-white md:grid-cols-[1fr_0.85fr] md:items-start">
        <div className="bg-[#eee4f4] md:order-2 md:m-5 md:overflow-hidden md:rounded-2xl">
          {headerImage ? <Image src={headerImage} alt="" width={460} height={215} unoptimized preload
            referrerPolicy="no-referrer" className="aspect-[460/215] h-auto w-full object-cover" />
            : <div className="grid min-h-20 place-items-center px-4 text-center text-sm text-[#514960]">Steam header image unavailable</div>}
        </div>
        <div className="min-w-0 p-5 sm:p-7 md:order-1 md:pr-0">
          <h1 className="break-words text-4xl font-bold leading-tight tracking-tight sm:text-5xl">{game.title}</h1>
          <p className="mt-3 text-base leading-relaxed text-[#514960]">{game.shortDescription ?? "Steam did not provide a short description."}</p>
          <dl className="mt-4 grid gap-2 text-sm">
            <div><dt className="inline font-bold">Genres </dt><dd className="inline text-[#514960]">{game.genres?.map(({ name }) => name).join(", ") || "Unavailable"}</dd></div>
            <div><dt className="inline font-bold">Platforms </dt><dd className="inline text-[#514960]">{game.platforms?.join(", ") || "Unavailable"}</dd></div>
            <div><dt className="inline font-bold">Release </dt><dd className="inline text-[#514960]">{game.releaseDate ?? (game.comingSoon ? "Coming soon" : "Date unavailable")}</dd></div>
          </dl>
        </div>
      </header>
      {staleRetrievedAt && <p role="status" className="rounded-xl border border-[#ead5ae] bg-[#fff0d8] px-4 py-3 text-sm text-[#694304]">
        <strong>Outdated Steam information.</strong> The last usable data was retrieved on{" "}
        <time dateTime={staleRetrievedAt}>{new Intl.DateTimeFormat("en-AU", { dateStyle: "long", timeZone: "Australia/Brisbane" }).format(new Date(staleRetrievedAt))}</time>.
        Check Steam and the official classification for current information.
      </p>}
      {incomplete && <p role="status" className="rounded-xl border border-[#e0d3e9] bg-[#f3eaf8] px-4 py-3 text-sm">
        Some Steam sources did not return data. The report uses the evidence available, and missing information remains unknown.
      </p>}
      <section aria-labelledby="overall-heading" className="rounded-3xl bg-[#352145] p-5 text-white sm:p-7">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <h2 id="overall-heading" className="text-2xl font-bold tracking-tight sm:text-3xl">Overall assessment</h2>
          <ReportStatus state={overview.status} label={overview.status === "significant_concern" ? "Significant concerns identified"
            : overview.status === "potential_concern" ? "Potential concerns identified" : "Insufficient information"} />
        </div>
        <p className="mt-4 max-w-3xl text-lg font-bold">{assessment.overallGuidance}</p>
        <p className="mt-2 max-w-3xl text-sm leading-relaxed text-[#f1e6f6] sm:text-base">{assessment.summary}</p>
        {overview.concerns.length > 0 && <div className="mt-5 border-t border-white/20 pt-4">
          <h3 className="mb-2 text-sm font-bold">Key concerns</h3>
          <ul className="flex flex-wrap gap-2">{overview.concerns.map((item) =>
            <li key={item.category}><a href={`#finding-${item.category}`} className="inline-flex min-h-11 items-center underline decoration-white/60 underline-offset-4">
              <ReportStatus state={item.state} label={item.label} />
            </a></li>)}</ul>
        </div>}
      </section>
      <div aria-label="Report actions" role="group" className="flex flex-wrap items-start gap-2">
        <SteamStoreLink appId={game.appId} />
        <ReportActions key={game.appId} appId={game.appId} title={game.title} url={SITE_URL + gameReportPath(game.appId, game.title)} />
      </div>
      <nav aria-label="In this report" className="flex flex-wrap gap-x-4 gap-y-1 px-1 text-sm font-bold text-[#563569]">
        {sections.map(([id, title]) => <a key={id} href={`#${id}`} className="inline-flex min-h-11 items-center underline underline-offset-4">{title}</a>)}
      </nav>
      <Classifications assessment={assessment} />
      <ReportSection id="content" title="Content suitability">{findings(content)}</ReportSection>
      <ReportSection id="online" title="Online safety">
        <h3 className="font-bold">Multiplayer features listed by Steam</h3>
        <p className="mb-3 mt-1 text-sm text-[#514960]">{multiplayer.length ? multiplayer.join(" · ") : "Multiplayer features are unknown in the available data."}</p>
        <p className="mb-4 text-sm text-[#514960]">{game.workshop
          ? "Steam Workshop is listed. Community content and modifications can differ from the base game."
          : "Steam Workshop availability and other ways to install modifications are unknown."}</p>
        {findings(["onlineInteraction", "userContent"])}
      </ReportSection>
      <ReportSection id="spending" title="Spending considerations">
        <p className="mb-4 text-sm text-[#514960]">{game.downloadableContent
          ? "Steam lists downloadable add-ons. This report does not establish whether they are free, paid, or included in a particular edition."
          : "Additional paid content is unknown in the available data."}</p>
        {findings(["purchases"])}
      </ReportSection>
      <ReportSection id="positive" title="Positive gameplay features">
        <p className="mb-2 text-sm text-[#514960]">Community tags can point to creative play, learning, exploration, problem-solving or local play. They describe reported features; they do not establish suitability or cancel concerns.</p>
        {positive.length > 0 ? <ul aria-label="Positive gameplay tags" className="mb-4 flex flex-wrap gap-2">
          {positive.map((tag) => <li key={tag} className="rounded-full bg-[#f2e9f8] px-3 py-1 text-sm font-bold text-[#563569]">{tag}</li>)}
        </ul> : <p className="mb-4 text-sm text-[#514960]">No relevant community tags were available.</p>}
        {findings(["positive"])}
      </ReportSection>
      <ReportSection id="transparency" title="How this report works">
        <p className="mb-2 text-sm text-[#514960]">Assessed <time dateTime={assessment.assessmentDate}>{assessment.assessmentDate.slice(0, 10)} UTC</time> · Rules version {assessment.rulesVersion}</p>
        <p className="mb-2 text-sm text-[#514960]">A versioned set of rules checks Australian English Steam data, including classification advice, developer disclosures, listed features and community tags. Community tags may support a finding but do not establish its severity.</p>
        <p className="mb-3 text-sm text-[#514960]">This report is informational. Store data may be incomplete or change by edition or region. Unknown evidence does not establish that a game is suitable. Check the official classification and consider your child and how they would play.</p>
        <Link href="/methodology" className="font-bold text-[#563569] underline underline-offset-4">Read the assessment methodology</Link>
      </ReportSection>
    </main>
  );
}
